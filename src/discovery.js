const SAFE_COMMAND = /^[a-zA-Z0-9_.-]+$/;

/** Comprobación ultrarrápida de si un comando existe en PATH (sin arrancar el runtime pesado del CLI). */
async function commandExists(command) {
  if (!SAFE_COMMAND.test(String(command ?? ''))) return false;
  const checker = process.platform === 'win32' ? 'where.exe' : 'which';
  const res = await runProcess(checker, [command], { timeoutMs: 3_000 });
  return res.code === 0 && Boolean(res.stdout.trim());
}

export async function probeCommand(command) {
  if (!SAFE_COMMAND.test(String(command ?? ''))) throw new Error('Indica un nombre de ejecutable de PATH, sin rutas ni espacios.');
  const exists = await commandExists(command);
  if (!exists) return { command, installed: false, version: null };
  const result = await runProcess(command, ['--version'], { timeoutMs: 6_000 });
  const out = (result.stdout || result.stderr || '').trim().split(/\r?\n/)[0]?.slice(0, 120);
  return {
    command,
    installed: true,
    version: out || 'instalado en PATH',
  };
}

export async function discoverAgents() {
  const results = await Promise.all(
    ORCA_CATALOG.map(async (item) => {
      const primary = await commandExists(item.command);
      const alt = !primary && item.altCommand ? await commandExists(item.altCommand) : false;
      const installed = primary || alt;
      return {
        ...item,
        resolvedCommand: alt ? item.altCommand : item.command,
        installed,
      };
    }),
  );
  return results;
}
